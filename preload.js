const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  onData: (cb) => ipcRenderer.on('data', (_e, d) => cb(d)),
  onHover: (cb) => ipcRenderer.on('hover', (_e, v) => cb(v)),
  onSettings: (cb) => ipcRenderer.on('settings', (_e, s) => cb(s)),
  refresh: () => ipcRenderer.send('refresh'),
  closePanel: () => ipcRenderer.send('close-panel'),
  hidePanel: () => ipcRenderer.send('hide-panel'),
  setCloseToTray: (v) => ipcRenderer.send('set-close-to-tray', v),
  setAutoUpdate: (v) => ipcRenderer.send('set-auto-update', v),
  setAlerts: (patch) => ipcRenderer.send('set-alerts', patch),
  setKeepAlive: (patch) => ipcRenderer.send('set-keepalive', patch),
  keepAliveTest: () => ipcRenderer.send('keepalive-test'),
  setAutoRefreshToken: (v) => ipcRenderer.send('set-auto-refresh-token', v),
  setAutostart: (v) => ipcRenderer.send('set-autostart', v),
  setTheme: (v) => ipcRenderer.send('set-theme', v),
  onboardDone: (opts) => ipcRenderer.send('onboard-done', opts),
  onUpdate: (cb) => ipcRenderer.on('update', (_e, u) => cb(u)),
  updateInstall: () => ipcRenderer.send('update-install'),
  updateDismiss: () => ipcRenderer.send('update-dismiss'),
  updateCheck: () => ipcRenderer.send('update-check'),
  toggleMain: () => ipcRenderer.send('toggle-main'),
  dockMenu: () => ipcRenderer.send('dock-menu'),
  dockResize: (w) => ipcRenderer.send('dock-resize', w),
  resize: (h) => ipcRenderer.send('resize', h),
  accountsSwitch: (id) => ipcRenderer.send('accounts-switch', id),
  accountsRename: (id, label) => ipcRenderer.send('accounts-rename', { id, label }),
  accountsRemove: (id) => ipcRenderer.send('accounts-remove', id),
  accountsSaveCurrent: (label) => ipcRenderer.send('accounts-save-current', label),
  accountsMenu: () => ipcRenderer.send('accounts-menu'),
  onAccounts: (cb) => ipcRenderer.on('accounts', (_e, a) => cb(a)),
});
